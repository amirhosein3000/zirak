"""Deterministic SYNTHETIC candles, used only until a real recorded sample replaces them.

They are clearly labelled synthetic in the UI and docs. The price path has a readable story for demos:
an uptrend, a range, a sharp drop, and a partial recovery. Price levels are rough placeholders.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta
from decimal import Decimal
from pathlib import Path

import numpy as np

from zirak.data.store import write_candles_csv
from zirak.markets import DEFAULT_MARKETS
from zirak.models import Candle, Market

END = datetime(2026, 10, 15, tzinfo=UTC)
DAYS = 75

# (daily drift %, hourly vol %) per phase, and phase length in days
PHASES = [(0.6, 0.55, 25), (0.0, 0.45, 20), (-4.0, 1.2, 3), (0.5, 0.7, 12), (0.1, 0.5, 15)]


def _path(start: float, rng: np.random.Generator, vol_scale: float = 1.0) -> np.ndarray:
    rets: list[float] = []
    for drift, vol, days in PHASES:
        hours = days * 24
        rets.extend(rng.normal(drift / 100 / 24, vol * vol_scale / 100, hours))
    return np.asarray(start * np.exp(np.cumsum(rets)))


def _candles(closes: np.ndarray, market: Market, rng: np.random.Generator, vol_base: float) -> list[Candle]:
    start = END - timedelta(hours=len(closes))
    out: list[Candle] = []
    prev = float(closes[0])
    for i, close in enumerate(closes):
        o = prev
        c = float(close)
        wick = abs(rng.normal(0, 0.25)) / 100
        h = max(o, c) * (1 + wick)
        lo = min(o, c) * (1 - abs(rng.normal(0, 0.25)) / 100)
        vol = vol_base * (1 + abs(rng.normal(0, 0.6))) * (1 + 8 * abs(c / o - 1) * 100 / 10)

        def p(x: float) -> Decimal:
            return market.round_price(Decimal(str(x)))

        out.append(Candle(start + timedelta(hours=i), p(o), p(h), p(lo), p(c),
                          market.round_qty(Decimal(str(vol)))))
        prev = c
    return out


def aggregate(candles: list[Candle], hours: int) -> list[Candle]:
    out: list[Candle] = []
    for i in range(0, len(candles) - hours + 1, hours):
        chunk = candles[i : i + hours]
        out.append(Candle(chunk[0].ts, chunk[0].open, max(c.high for c in chunk), min(c.low for c in chunk),
                          chunk[-1].close, sum((c.volume for c in chunk), Decimal(0))))
    return out


def generate(directory: Path, seed: int = 7) -> list[Path]:
    rng = np.random.default_rng(seed)
    usdt = 105_000 * np.exp(np.cumsum(rng.normal(0.0004 / 24, 0.0015, DAYS * 24)))
    btc_usdt = _path(98_000, rng)
    eth_usdt = _path(3_600, rng, vol_scale=1.3)
    series = {
        "USDTTMN": (usdt, 40_000.0),
        "BTCUSDT": (btc_usdt, 12.0),
        "ETHUSDT": (eth_usdt, 300.0),
        "BTCTMN": (btc_usdt * usdt, 1.5),
        "ETHTMN": (eth_usdt * usdt, 40.0),
    }
    written: list[Path] = []
    for symbol, (closes, vol) in series.items():
        market = DEFAULT_MARKETS[symbol]
        hourly = _candles(closes, market, rng, vol)
        for res, hours in (("1h", 1), ("4h", 4), ("1d", 24)):
            path = directory / f"{symbol}_{res}.csv"
            write_candles_csv(path, hourly if hours == 1 else aggregate(hourly, hours))
            written.append(path)
    (directory / "README.md").write_text(
        "# SYNTHETIC sample data\n\n"
        "Generated by `zirak make-sample` (seed 7). Not real market data.\n"
        "Replace with a real recorded sample once the Wallex recorder runs (see docs/progress.md).\n",
        encoding="utf-8",
    )
    return written
